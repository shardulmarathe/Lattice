/** Regenerate src/data/puzzles.ts from the ordered list of registered draft ids. */
export function writePuzzlesIndex(draftIds: number[]): void {
  const ordered = [...draftIds].sort((a, b) => a - b);
  const imports = ordered
    .map((id) => `import { ${puzzleSymbol(id)} } from "./drafts/${puzzleStem(id)}";`)
    .join("\n");
  const arrayEntries = ["  PUZZLE_001", ...ordered.map((id) => `  ${puzzleSymbol(id)}`)].join(
    ",\n"
  );
  const reExports = ordered
    .map((id) => `export { ${puzzleSymbol(id)} } from "./drafts/${puzzleStem(id)}";`)
    .join("\n");

  const content = `${GENERATED_HEADER}
import type { Puzzle } from "@/lib/puzzleTypes";
${imports}
import { getScheduledPuzzleId } from "./schedule";

${INLINE_PUZZLE_001}

export const PUZZLES: Puzzle[] = [
${arrayEntries},
];

${reExports}

export function getPuzzleById(id: number): Puzzle | undefined {
  return PUZZLES.find((p) => p.id === id);
}

export function getPuzzleByIndex(index: number): Puzzle {
  return PUZZLES[index] ?? PUZZLE_001;
}

export function getPuzzleForDate(date: Date): Puzzle | undefined {
  const id = getScheduledPuzzleId(date);
  if (id === undefined) return undefined;
  return getPuzzleById(id);
}
`;
  writeFileSync(join(DATA_DIR, "puzzles.ts"), content);
}

/** Regenerate src/data/schedule.ts from the schedule map. */
export function writeScheduleModule(schedule: Record<string, number>): void {
  const entries = Object.keys(schedule)
    .sort()
    .map((date) => `  ${JSON.stringify(date)}: ${schedule[date]},`)
    .join("\n");

  const content = `${GENERATED_HEADER}
// Source of truth: src/data/schedule.json
/** Maps calendar dates (YYYY-MM-DD) to puzzle ids. */
export const PUZZLE_SCHEDULE: Record<string, number> = {
${entries}
};

export function formatDateKey(date: Date): string {
  const year = date.getFullYear();
  const month = String(date.getMonth() + 1).padStart(2, "0");
  const day = String(date.getDate()).padStart(2, "0");
  return \`\${year}-\${month}-\${day}\`;
}

export function getScheduledPuzzleId(date: Date): number | undefined {
  return PUZZLE_SCHEDULE[formatDateKey(date)];
}
`;
  writeFileSync(join(DATA_DIR, "schedule.ts"), content);
}

export function readScheduleJson(): Record<string, number> | null {
  if (!existsSync(SCHEDULE_JSON)) return null;
  return JSON.parse(readFileSync(SCHEDULE_JSON, "utf8"));
}

export function writeScheduleJson(schedule: Record<string, number>): void {
  const sorted: Record<string, number> = {};
  for (const date of Object.keys(schedule).sort()) sorted[date] = schedule[date];
  writeFileSync(SCHEDULE_JSON, JSON.stringify(sorted, null, 2) + "\n");
}

/**
 * Codegen: turn generated puzzle data into committed source files.
 *
 * Everything the app imports is regenerated wholesale from a source of truth
 * (src/data/schedule.json + the draft files) rather than append-patched, so the
 * output is deterministic and diff-friendly.
 */

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import type { MirrorPlacement, Puzzle } from "../../src/lib/puzzleTypes";
import type { GeneratedPuzzle } from "./generator";

export const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const DATA_DIR = join(REPO_ROOT, "src", "data");
const DRAFTS_DIR = join(DATA_DIR, "drafts");
const SOLUTIONS_DIR = join(REPO_ROOT, "content", "solutions");
export const SCHEDULE_JSON = join(DATA_DIR, "schedule.json");

/** id → PUZZLE_NNN symbol / puzzle-NNN filename stem (3-digit zero-padded). */
export function puzzleStem(id: number): string {
  return `puzzle-${String(id).padStart(3, "0")}`;
}
export function puzzleSymbol(id: number): string {
  return `PUZZLE_${String(id).padStart(3, "0")}`;
}

const GENERATED_HEADER =
  "// AUTO-GENERATED by scripts/puzzles/generate.ts — do not edit by hand.";

function serializePuzzleBody(puzzle: Puzzle): string {
  const numbers = puzzle.numbers
    .map((n) => `    { value: ${n.value}, x: ${n.x}, y: ${n.y} },`)
    .join("\n");
  const obstacles = puzzle.obstacles
    .map((o) => `    { x: ${o.x}, y: ${o.y} },`)
    .join("\n");
  return [
    `  id: ${puzzle.id},`,
    `  code: ${JSON.stringify(puzzle.code)},`,
    `  gridSize: ${puzzle.gridSize},`,
    `  source: { x: ${puzzle.source.x}, y: ${puzzle.source.y}, direction: ${JSON.stringify(
      puzzle.source.direction
    )} },`,
    `  flag: { x: ${puzzle.flag.x}, y: ${puzzle.flag.y} },`,
    `  numbers: [\n${numbers}\n  ],`,
    `  obstacles: [${obstacles ? `\n${obstacles}\n  ` : ""}],`,
  ].join("\n");
}

export function writeDraftFile(
  puzzle: Puzzle,
  scheduledDate: string,
  generated: GeneratedPuzzle
): void {
  const area = puzzle.gridSize * puzzle.gridSize;
  const density = ((generated.solution.length / area) * 100).toFixed(0);
  const content = `import type { Puzzle } from "@/lib/puzzleTypes";

${GENERATED_HEADER}
/** Scheduled ${scheduledDate} (extra hard). ${puzzle.gridSize}×${puzzle.gridSize}, ${puzzle.code.length}-digit code, intended ${generated.solution.length}-mirror solution (${density}% density), no ≤${generated.grade.cap}-mirror shortcut. */
export const ${puzzleSymbol(puzzle.id)}: Puzzle = {
${serializePuzzleBody(puzzle)}
};
`;
  writeFileSync(join(DRAFTS_DIR, `${puzzleStem(puzzle.id)}.ts`), content);
}

export interface SolutionSidecar {
  id: number;
  scheduledDate: string;
  code: string;
  gridSize: number;
  seed: string;
  solutionMirrors: MirrorPlacement[];
  mirrorCount: number;
  mirrorDensity: number | null;
  solverCap: number;
  /** Exact minimum mirror count, when a full search found one within the cap. */
  minMirrors?: number;
  /** Lower bound (cap + 1) when no solution was found within the cap. */
  minMirrorsAtLeast?: number;
  pathLength: number | null;
  obstacleInterference: number;
  score: number;
}

export function writeSolutionSidecar(sidecar: SolutionSidecar): void {
  if (!existsSync(SOLUTIONS_DIR)) mkdirSync(SOLUTIONS_DIR, { recursive: true });
  writeFileSync(
    join(SOLUTIONS_DIR, `${puzzleStem(sidecar.id)}.json`),
    JSON.stringify(sidecar, null, 2) + "\n"
  );
}

